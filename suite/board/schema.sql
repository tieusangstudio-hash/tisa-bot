CREATE TABLE IF NOT EXISTS docs (col TEXT NOT NULL, id TEXT NOT NULL, data TEXT NOT NULL, ver INTEGER NOT NULL, PRIMARY KEY (col, id));
CREATE INDEX IF NOT EXISTS docs_ver ON docs(ver);
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v INTEGER NOT NULL);
INSERT OR IGNORE INTO meta (k, v) VALUES ('ver', 1);
CREATE TABLE IF NOT EXISTS blobs (id TEXT PRIMARY KEY, type TEXT, name TEXT, size INTEGER, created TEXT);
